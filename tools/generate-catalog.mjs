import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const catalogDirectory = join(root, "packages", "activity-catalog", "src", "catalog");
const outputPath = join(root, "packages", "activity-catalog", "src", "generated.ts");
const files = (await readdir(catalogDirectory))
  .filter((file) => file.endsWith(".json"))
  .sort();

const activities = [];
for (const file of files) {
  const raw = await readFile(join(catalogDirectory, file), "utf8");
  activities.push(JSON.parse(raw));
}

const output = [
  "/* This file is generated by tools/generate-catalog.mjs. */",
  'import type { ActivityDefinition } from "@activityweaver/protocol";',
  "",
  "export const builtInActivities: ActivityDefinition[] = " + JSON.stringify(activities, null, 2) + ";",
  ""
].join("\n");

await writeFile(outputPath, output, "utf8");
console.log("Generated " + activities.length + " activity definitions.");
